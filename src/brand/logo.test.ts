import { describe, expect, it } from "vitest";
import { DARK_THEME, FAVICON_OPTIONS, growTree, markInner, markSvg } from "./logo";

describe("logo is generated by recursion", () => {
  it("branch() makes a full binary tree", () => {
    const d3 = growTree(3, 100);
    expect(d3.segments).toHaveLength(1 + 2 + 4 + 8);
    expect(d3.tips).toHaveLength(8);
    const d2 = growTree(2, 100);
    expect(d2.tips).toHaveLength(4);
  });

  it("strokes taper from trunk to twigs", () => {
    const { segments } = growTree(3, 100);
    expect(segments[0].w1).toBeGreaterThan(segments[segments.length - 1].w2 * 4);
  });

  it("exactly one tip glows in the accent colour", () => {
    const svg = markInner({ theme: DARK_THEME }).svgInner;
    const accentFills = svg.match(new RegExp(`fill="${DARK_THEME.accent}"`, "g")) ?? [];
    expect(accentFills).toHaveLength(1);
  });

  it("is deterministic and has no gradients or filters", () => {
    expect(markSvg()).toBe(markSvg());
    expect(markSvg()).not.toMatch(/Gradient|filter|feGaussian/);
  });

  it("favicon variant is depth 2 on a 32px box", () => {
    const fav = markInner({ ...FAVICON_OPTIONS, theme: DARK_THEME });
    expect(fav.tipCount).toBe(4);
    expect(markSvg(FAVICON_OPTIONS)).toContain('viewBox="0 0 32 32"');
  });
});
